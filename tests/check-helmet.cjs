const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'../dist');
const dom=new JSDOM('<div class="hero-portrait"></div>',{runScripts:'outside-only'});
const w=dom.window,d=w.document;
// Keep test device capabilities explicit; CI runners may only expose two cores.
Object.defineProperty(w.navigator,'hardwareConcurrency',{value:8,configurable:true});
w.matchMedia=()=>({matches:false});
let pauses=0,resumes=0;
w.SVGSVGElement.prototype.pauseAnimations=function(){pauses++;};
w.SVGSVGElement.prototype.unpauseAnimations=function(){resumes++;};
w.eval(fs.readFileSync(path.join(root,'helmet-ink.js'),'utf8'));
const api=w.HelmetInk,mesh=api.buildMesh();
assert.ok(mesh.edges.length>7000&&mesh.edges.length<10000,'fine triangular wireframe has a bounded complexity');
assert.ok(mesh.edges.every(edge=>edge.every(i=>i>=0&&i<mesh.points.length)));
assert.ok(mesh.points.every(p=>p.every(Number.isFinite)&&p[0]>=0&&p[0]<=1448&&p[1]>=0&&p[1]<=1086));
const portrait=d.querySelector('.hero-portrait'),ink=api.mount(portrait),svg=portrait.querySelector('svg');
assert.equal(api.mount(portrait),ink,'only one outline is mounted');
assert.equal(svg.getAttribute('viewBox'),'0 0 1448 1086');
assert.equal(svg.querySelectorAll('clipPath path').length,2,'shell and clear jaw shield clip the mesh away from hair/body');
assert.equal(svg.querySelector('g').getAttribute('fill'),'none','the visible helmet has no opaque body');
assert.ok([...svg.querySelectorAll('stop')].every(s=>+s.getAttribute('stop-opacity')<=.12),'ink stays very faint like the reference');
assert.ok(svg.querySelector('animateTransform'),'wireframe has a gentle scan instead of rotating the shell');
ink.setActive(false);assert.equal(pauses,1);ink.setActive(false);assert.equal(pauses,1);
ink.setActive(true);assert.equal(resumes,1);
ink.setThumbnail(.5);assert.ok(+svg.style.opacity>0&&+svg.style.opacity<.5);
ink.setThumbnail(1);assert.equal(svg.style.opacity,'0','wireframe clears completely in the gray thumbnail');
ink.setThumbnail(0);assert.equal(svg.style.opacity,'1');
const webp=fs.readFileSync(path.join(root,'assets/hero-helmet.webp'));
assert.equal(webp.subarray(8,12).toString(),'WEBP');
assert.equal(webp.subarray(12,16).toString(),'VP8L','photo remains lossless');
const dimensions=webp.readUInt32LE(21);
assert.equal((dimensions&0x3fff)+1,1448);assert.equal(((dimensions>>>14)&0x3fff)+1,1086,'outline and original photo share exact coordinates');
const compact=api.buildMesh(true);assert.ok(compact.edges.length<1700&&compact.edges.length>1400,'mobile retains the traced silhouette with less than one fifth of the mesh segments');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(html.indexOf('helmet-ink.js')<html.indexOf('fluid-hero.js'));
assert.ok(!html.includes('helmet-orbit.js'),'solid orbit renderer is removed');
ink.remove();
Object.defineProperty(w.navigator,'hardwareConcurrency',{value:2,configurable:true});
const light=api.mount(portrait),compactSvg=portrait.querySelector('svg');
assert.equal(compactSvg.dataset.quality,'compact');assert.equal(compactSvg.querySelector('animateTransform'),null,'low-core devices keep the ink structure without continuous scanning');
light.setActive(false);light.setActive(true);assert.equal(compactSvg.dataset.motion,'static');
dom.window.close();console.log('PASS photo-aligned helmet outline, clipped fine mesh, faint ink scan, pause/resume, gray-thumbnail fade and no solid 3D renderer');
